"""
The initial atomic velocity components are generated from the Maxwell-Boltzmann distribution
using pseudo-random numbers generated by a Linear Congruential Generator (LCG) and the
Box-Muller transform.

Usage:
    python initial_velocities.py entry.xyz --temperature 300 --seed 123456 --output output.xyz

References:
    Leach, A. R. Molecular Modelling: Principles and Applications.
    Prentice Hall, 2nd ed., 2001.
 
    Box, G. E. P.; Muller, M. E. A Note on the Generation of Random
    Normal Deviates. The Annals of Mathematical Statistics, v. 29,
    n. 2, p. 610-611, 1958.

"""
import sys
import argparse
from pathlib import Path
import constants
import re
import numpy as np

class Atom:
    def __init__(self,
                 symbol: str,
                 mass: float,
                 pos_x: float,
                 pos_y: float,
                 pos_z: float) -> None:
        """
        Represents a single atom with position and velocity.

        Parameters
        ----------
        symbol : str
            Atomic symbol (e.g. 'C', 'H', 'O').
        mass : float
            Atomic mass in atomic mass units (amu).
        pos_x : float
            Position in x-direction in Angstroms.
        pos_y : float
            Position in y-direction in Angstroms.
        pos_z : float
            Position in z-direction in Angstroms.
        """
        self.symbol = symbol
        self.mass   = mass
        self.pos_x  = pos_x
        self.pos_y  = pos_y
        self.pos_z  = pos_z

        # Velocities are set later by the MB generator
        self.vel_x: float = 0.0
        self.vel_y: float = 0.0
        self.vel_z: float = 0.0

    def set_velocities(self, vx: float, vy: float, vz: float) -> None:
        """
        Set the three velocity components at once.

        Parameters
        ----------
        vx : float
            Velocity in x-direction.
        vy : float
            Velocity in y-direction.
        vz : float
            Velocity in z-direction.
        """
        self.vel_x = vx
        self.vel_y = vy
        self.vel_z = vz

    def __repr__(self) -> str:
        return (
            f"Atom({self.symbol}, m={self.mass:.4f}, "
            f"pos=({self.pos_x:.4f}, {self.pos_y:.4f}, {self.pos_z:.4f}), "
            f"vel=({self.vel_x:.4f}, {self.vel_y:.4f}, {self.vel_z:.4f}))")


class LinearCongruentialGenerator:    
    def __init__(self,
                 seed: int = 123456,
                 a: int = 1664525,
                 c: int = 1013904223,
                 m: int = 2**32) -> None:
        """
        Linear Congruential Generator (LCG) for pseudo-random number generation.

        The recurrence relation is: x_(n+1) = (a * x_n + c) mod m

        Parameters
        ----------
        seed : int, optional
            Initial state of the generator. Default: 123456.
        a : int, optional
            Multiplier. Default: 1664525 (Numerical Recipes).
        c : int, optional
            Increment. Default: 1013904223 (Numerical Recipes).
        m : int, optional
            Modulus. Default: 2**32.
        """
        self.state = seed
        self.a = a
        self.c = c
        self.m = m

    def random_int(self) -> int:
        """
        Generate the next pseudo-random integer in the sequence.

        Returns
        -------
        int
            Pseudo-random integer in the range [0, m).
        """
        self.state = (self.a * self.state + self.c) % self.m
        return self.state
    
    def random_norm(self) -> float:
        """
        Generate the next pseudo-random number normalized to [0, 1).

        Returns
        -------
        float
            Pseudo-random float in the range [0, 1).
        """
        return self.random_int() / self.m

